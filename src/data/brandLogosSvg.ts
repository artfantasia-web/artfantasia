// Generates a crisp fallback SVG badge for any custom logo
export function generateFallbackSvg(name: string): string {
  const cleanName = (name || 'PARTNER').trim();
  const palette = ['#002c5f', '#034ea2', '#a50034', '#ea002c', '#003974', '#005bac', '#004b87', '#03c75a', '#1e293b'];
  let hash = 0;
  for (let i = 0; i < cleanName.length; i++) {
    hash = (hash << 5) - hash + cleanName.charCodeAt(i);
    hash |= 0;
  }
  const color = palette[Math.abs(hash) % palette.length];

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 36" width="160" height="36">
    <rect x="6" y="6" width="24" height="24" rx="6" fill="${color}" fill-opacity="0.12" stroke="${color}" stroke-width="1.5"/>
    <text x="18" y="22" text-anchor="middle" font-family="'Pretendard', Arial, sans-serif" font-weight="900" font-size="13" fill="${color}">${cleanName.charAt(0).toUpperCase()}</text>
    <text x="36" y="23" font-family="'Pretendard', -apple-system, sans-serif" font-weight="800" font-size="13" fill="${color}" letter-spacing="0.5">${cleanName}</text>
  </svg>`;
}

// Retrieves the high-definition SVG logo for a given logo item
export function getBrandLogoSvg(id: string, name: string): string {
  if (BRAND_SVG_MAP[id]) {
    return BRAND_SVG_MAP[id];
  }
  // Try case-insensitive matching by name keywords
  const lowerName = name.toLowerCase();
  for (const [key, svg] of Object.entries(BRAND_SVG_MAP)) {
    const rawKey = key.replace('logo-', '');
    if (lowerName.includes(rawKey)) {
      return svg;
    }
  }
  return generateFallbackSvg(name);
}
